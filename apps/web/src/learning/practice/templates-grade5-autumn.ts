import { GRADE5_AUTUMN_MATH_COURSE } from '../content/course-registry'
import type { Difficulty, QuestionOption, QuestionType } from '../types'
import {
  defineMathTemplate,
  type MathPaperCategory,
  type MathQuestionTemplate,
} from './math-template-kit'

function g5a(
  id: string,
  knowledgePointId: string,
  unitId: string,
  generator: string,
  type: QuestionType,
  difficulty: Difficulty,
  supportedDifficulties: readonly Difficulty[],
  promptTemplate: string,
  paperCategory: MathPaperCategory,
  options?: readonly QuestionOption[],
): MathQuestionTemplate {
  return defineMathTemplate(GRADE5_AUTUMN_MATH_COURSE, {
    id,
    knowledgePointId,
    unitId,
    generator,
    type,
    difficulty,
    supportedDifficulties,
    promptTemplate,
    paperCategory,
    ...(options ? { options } : {}),
  })
}


export function getCourseById(courseId: string): Course | undefined {
  return COURSE_REGISTRY.find((course) => course.id === courseId)
}

export function getCourseAvailability(
  grade: number,
  semester: Semester,
  subject: Subject,
): CourseAvailability | undefined {
  return COURSE_AVAILABILITY.find(
    (availability) =>
      availability.grade === grade &&
      availability.semester === semester &&
      availability.subject === subject,
  )
}

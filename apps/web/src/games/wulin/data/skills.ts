import type { ActiveSkill, BasicKind, SkillDef, SkillMove, SkillSlot, WeaponType } from '../types'

const mv = (name: string, atk: number, dmg: number, pre: number, post: number): SkillMove => ({
  name,
  atk,
  dmg,
  pre,
  post,
})

const act = (
  name: string,
  pages: number,
  mp: number,
  cd: number,
  kind: ActiveSkill['kind'],
  power: number,
  desc: string,
): ActiveSkill => ({ name, pages, mp, cd, kind, power, desc })

interface MkOpts {
  id: string
  name: string
  sect?: string | null
  tier: SkillDef['tier']
  slots: SkillSlot[]
  basic?: BasicKind | null
  weapon?: WeaponType | null
  conv: number
  atk?: number
  dmg?: number
  hit?: number
  pAtk?: number
  def?: number
  dodge?: number
  speed?: number
  hp?: number
  mp?: number
  learn?: { potential?: number; silver?: number; contribution?: number }
  moves?: SkillMove[]
  active?: ActiveSkill | null
  desc: string
}

function mk(o: MkOpts): SkillDef {
  return {
    id: o.id,
    name: o.name,
    sect: o.sect ?? null,
    tier: o.tier,
    slots: o.slots,
    basic: o.basic ?? null,
    weapon: o.weapon ?? null,
    conversion: o.conv,
    atkCoef: o.atk ?? 0,
    dmgCoef: o.dmg ?? 0,
    hitCoef: o.hit ?? 50,
    pAtkCoef: o.pAtk ?? 0,
    defCoef: o.def ?? 0,
    dodgeCoef: o.dodge ?? 0,
    speedCoef: o.speed ?? 10,
    hpCoef: o.hp ?? 0,
    mpCoef: o.mp ?? 0,
    learn: {
      potential: o.learn?.potential ?? 0,
      silver: o.learn?.silver ?? 0,
      contribution: o.learn?.contribution ?? 0,
    },
    moves: o.moves ?? [mv('调息', 0.3, 0, 0.8, 0.8)],
    active: o.active ?? null,
    desc: o.desc,
  }
}

